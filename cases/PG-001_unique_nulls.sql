-- PG-001: UNIQUE NULLS NOT DISTINCT (PG15+)
DROP TABLE IF EXISTS t_uniq;
CREATE TABLE t_uniq (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT
);
CREATE UNIQUE INDEX t_uniq_email_uidx ON t_uniq (email) NULLS NOT DISTINCT;

INSERT INTO t_uniq (email) VALUES ('a@x.com');
INSERT INTO t_uniq (email) VALUES (NULL);
-- Second NULL should fail under NULLS NOT DISTINCT
-- Runner expects SQLSTATE 23505 on the next insert; we probe with a DO block.
DO $$
BEGIN
  BEGIN
    INSERT INTO t_uniq (email) VALUES (NULL);
    RAISE EXCEPTION 'expected unique violation not raised';
  EXCEPTION WHEN unique_violation THEN
    RAISE NOTICE 'ok_unique_violation';
  END;
END $$;
SELECT COUNT(*) AS n FROM t_uniq;
